//! SQLite-backed persistence for the desktop shell.
//!
//! So far all preferences lived in webview `localStorage` under versioned
//! `vlc.*.v1` keys. Those blobs are invisible to Rust, bound to the webview
//! profile and quietly size-limited. The database mirrors the same keys
//! one-to-one in a `kv` table so front-end stores can adopt SQLite without
//! reshaping their data; WAL keeps writes crash-safe in the single file at
//! `app_data_dir/kanea.db`. When a domain outgrows its JSON blob the table
//! can be normalized later without moving the file.
//!
//! A second domain lives here from the start: JPEG frame thumbnails are
//! generated by the Rust pipeline (`thumb.rs`) and stored as blobs in the
//! `thumbnails` table, keyed by the media item's absolute file path, so no
//! webview capture or base64 persist round-trip is ever needed for them.
//!
//! A third domain, same story: embedded audio cover art is extracted by
//! `audio_meta.rs` and stored as blobs in the `covers` table, keyed the same
//! way. Cover blobs are kept in their own table rather than in `thumbnails`
//! under a `cover:` key prefix: the two tables are separate domains (video
//! frames vs. artwork), and prefix-stuffing a file-path primary key would
//! conflate the key namespaces.
//!
//! A fourth domain, same story: audio waveform peaks are decoded by
//! `waveform.rs` and stored as little-endian f32 blobs in the `waveforms`
//! table, keyed the same way, in yet another separate table so the domains
//! (video frames, artwork, seekbar peaks) never share a namespace.
//!
//! A fifth domain: container durations probed by `duration.rs` (ffmpeg `-i`,
//! no decode) live in the `durations` table as REAL seconds, keyed the same
//! way, so library cards do not re-probe a file on every scan.

use rusqlite::{Connection, OptionalExtension, params};
use std::sync::Mutex;
use std::time::{SystemTime, UNIX_EPOCH};
use tauri::State;

/// Connection state shared across command calls.
pub struct Database(pub(crate) Mutex<Connection>);

/// Create the persistence schema (`kv`, `thumbnails`, `covers`, `waveforms`,
/// `durations`). Idempotent.
pub(crate) fn init_schema(conn: &Connection) -> rusqlite::Result<()> {
    conn.execute_batch(
        "CREATE TABLE IF NOT EXISTS kv (
            key        TEXT PRIMARY KEY,
            value      TEXT NOT NULL,
            updated_at INTEGER NOT NULL
        );",
    )?;
    conn.execute_batch(
        "CREATE TABLE IF NOT EXISTS thumbnails (
            path       TEXT PRIMARY KEY,
            data       BLOB NOT NULL,
            updated_at INTEGER NOT NULL
        );",
    )?;
    conn.execute_batch(
        "CREATE TABLE IF NOT EXISTS covers (
            path       TEXT PRIMARY KEY,
            data       BLOB NOT NULL,
            updated_at INTEGER NOT NULL
        );",
    )?;
    conn.execute_batch(
        "CREATE TABLE IF NOT EXISTS waveforms (
            path       TEXT PRIMARY KEY,
            peaks      BLOB NOT NULL,
            buckets    INTEGER NOT NULL,
            updated_at INTEGER NOT NULL
        );",
    )?;
    conn.execute_batch(
        "CREATE TABLE IF NOT EXISTS durations (
            path       TEXT PRIMARY KEY,
            seconds    REAL NOT NULL,
            updated_at INTEGER NOT NULL
        );",
    )
}

pub(crate) fn open_connection(path: &std::path::Path) -> rusqlite::Result<Connection> {
    let conn = Connection::open(path)?;
    // WAL keeps writes durable without blocking readers; NORMAL is the usual
    // SQLite recommendation for WAL and significantly reduces fsync cost.
    //
    // Both pragmas are read through `.optional()`: `PRAGMA journal_mode`
    // returns one row, but `PRAGMA synchronous = NORMAL` (and several other
    // write-only pragma assignments) return NO rows at all, so a plain
    // `query_row` would fail the whole open with `QueryReturnedNoRows` —
    // which surfaced as a panicking setup hook on app start. What matters is
    // that the pragma executed, not that it echoed a value.
    let _: Option<String> = conn
        .query_row("PRAGMA journal_mode = WAL", [], |row| row.get(0))
        .optional()?;
    let _: Option<String> = conn
        .query_row("PRAGMA synchronous = NORMAL", [], |row| row.get(0))
        .optional()?;
    init_schema(&conn)?;
    Ok(conn)
}

/// Open (creating if needed) the database at `app_data_dir/kanea.db`.
pub fn open_database(handle: &tauri::AppHandle) -> Result<Database, Box<dyn std::error::Error>> {
    use tauri::Manager;

    let dir = handle.path().app_data_dir()?;
    std::fs::create_dir_all(&dir)?;
    let conn = open_connection(&dir.join("kanea.db"))?;
    Ok(Database(Mutex::new(conn)))
}

fn kv_get(conn: &Connection, key: &str) -> rusqlite::Result<Option<String>> {
    conn.query_row(
        "SELECT value FROM kv WHERE key = ?1",
        params![key],
        |row| row.get(0),
    )
    .optional()
}

fn kv_set(conn: &Connection, key: &str, value: &str) -> rusqlite::Result<usize> {
    let now = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_millis() as i64;

    conn.execute(
        "INSERT INTO kv (key, value, updated_at)
         VALUES (?1, ?2, ?3)
         ON CONFLICT(key) DO UPDATE SET
             value = excluded.value,
             updated_at = excluded.updated_at",
        params![key, value, now],
    )
}

/// Read a stored JSON blob. `None` means the key has never been written.
#[tauri::command]
pub fn db_get(state: State<'_, Database>, key: String) -> Result<Option<String>, String> {
    let conn = state.0.lock().map_err(|_| "database is locked".to_string())?;
    kv_get(&conn, &key).map_err(|e| e.to_string())
}

/// Write a JSON blob, replacing any previous value for the key.
#[tauri::command]
pub fn db_set(state: State<'_, Database>, key: String, value: String) -> Result<(), String> {
    let conn = state.0.lock().map_err(|_| "database is locked".to_string())?;
    kv_set(&conn, &key, &value).map(|_| ()).map_err(|e| e.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn test_conn() -> Connection {
        let conn = Connection::open_in_memory().unwrap();
        init_schema(&conn).unwrap();
        conn
    }

    /// Regression: the real open path must survive the pragma reads.
    ///
    /// `PRAGMA synchronous = NORMAL` returns no rows; before the
    /// `.optional()` fix that error escaped `open_connection` and panicked
    /// the Tauri setup hook (`Query returned no rows`). This test exercises
    /// the exact file-db shape the app uses and also pins the WAL mode and
    /// the full schema (`kv` + `thumbnails`).
    #[test]
    fn test_open_connection_sets_pragmas_and_schema() {
        let dir = std::env::temp_dir().join("kanea_test_open_connection");
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();

        let conn = open_connection(&dir.join("kanea.db")).expect("open_connection failed");

        // WAL mode is actually active on the file database.
        let journal_mode: String = conn
            .query_row("PRAGMA journal_mode", [], |row| row.get(0))
            .unwrap();
        assert_eq!(journal_mode, "wal");

        // All persistence tables exist after opening.
        for table in ["kv", "thumbnails", "covers", "waveforms"] {
            let count: i64 = conn
                .query_row(
                    "SELECT COUNT(*) FROM sqlite_master WHERE type = 'table' AND name = ?1",
                    params![table],
                    |row| row.get(0),
                )
                .unwrap();
            assert_eq!(count, 1, "table {table} missing after open");
        }

        // Normal synchronous level: 1 = NORMAL (value the pragma set).
        let synchronous: i64 = conn
            .query_row("PRAGMA synchronous", [], |row| row.get(0))
            .unwrap();
        assert_eq!(synchronous, 1);

        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn test_kv_roundtrip() {
        let conn = test_conn();
        assert_eq!(kv_get(&conn, "vlc.settings.v1").unwrap(), None);

        kv_set(&conn, "vlc.settings.v1", r#"{"theme":"dark"}"#).unwrap();
        assert_eq!(
            kv_get(&conn, "vlc.settings.v1").unwrap().as_deref(),
            Some(r#"{"theme":"dark"}"#)
        );
    }

    #[test]
    fn test_kv_upsert_replaces_value() {
        let conn = test_conn();
        kv_set(&conn, "vlc.watch.v1", r#"{"a":1}"#).unwrap();
        kv_set(&conn, "vlc.watch.v1", r#"{"a":2}"#).unwrap();
        assert_eq!(
            kv_get(&conn, "vlc.watch.v1").unwrap().as_deref(),
            Some(r#"{"a":2}"#)
        );

        // Exactly one row per key, never two after upserts.
        let count: i64 = conn
            .query_row("SELECT COUNT(*) FROM kv", [], |row| row.get(0))
            .unwrap();
        assert_eq!(count, 1);
    }

    #[test]
    fn test_kv_keys_are_independent() {
        let conn = test_conn();
        kv_set(&conn, "vlc.settings.v1", "one").unwrap();
        kv_set(&conn, "vlc.history.v1", "two").unwrap();
        assert_eq!(kv_get(&conn, "vlc.settings.v1").unwrap().as_deref(), Some("one"));
        assert_eq!(kv_get(&conn, "vlc.history.v1").unwrap().as_deref(), Some("two"));
    }
}
